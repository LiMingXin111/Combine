_ALL = {**CITIES, **PLACES}


def resolve(name: str) -> tuple[float, float] | None:
    """地名 → (lat, lng)。先精确匹配；再退化为包含匹配——
    复合名如「杭州西湖」取**位置最靠后**的命中项（城市前缀 + 具体地点），并列时取更长者。"""
    n = str(name or "").strip()
    if not n:
        return None
    if n in _ALL:
        return _ALL[n]
    hits = [k for k in _ALL if k in n or (len(n) >= 2 and n in k)]
    if not hits:
        return None
    return _ALL[max(hits, key=lambda k: (n.rfind(k), len(k)))]


def resolve_many(names: list[str]) -> list[dict]:
    """批量解析：每个名字都返回一条（未命中时 found=false），供工具结果回传模型。"""
    out = []
    for raw in names:
        n = str(raw or "").strip()
        if not n:
            continue
        hit = resolve(n)
        item = {"name": n, "found": bool(hit)}
        if hit:
            item["lat"], item["lng"] = round(hit[0], 5), round(hit[1], 5)
            city = next((c for c, v in CITIES.items() if abs(v[0] - hit[0]) < 1.2 and abs(v[1] - hit[1]) < 1.2), "")
            if city:
                item["city"] = city
        out.append(item)
    return out

import { useState, type ReactNode } from "react";
import {
  ArrowUpRight,
  Download,
  Loader2,
  Maximize2,
  Minimize2,
} from "lucide-react";
import { Markdown } from "./AssistantPanel";
import WebSources from "./WebSources";
import { download, rpc } from "./api";
type Any = Record<string, any>;

export default function FinalAnswerPanel({
  detail,
  draft,
  expanded,
  onExpand,
  onFocus,
  renderOutput,
}: {
  detail: Any | null;
  draft: boolean;
  expanded: boolean;
  onExpand: () => void;
  onFocus: (id: string) => void;
  renderOutput: (value: Any) => ReactNode;
}) {
  const [exporting, setExporting] = useState(false),
    [error, setError] = useState("");
  const final = detail?.final;
  if (draft)
    return (
      <div className="final-answer-empty">
        Apply your draft, then run the workflow to generate its final answer.
      </div>
    );
  if (!detail)
    return (
      <div className="final-answer-empty">
        Run a connected workflow to see its final answer here.
      </div>
    );
  if (final?.state !== "ready")
    return (
      <div className="final-answer-empty">
        <strong>
          {final?.state === "blocked"
            ? "Final answer is blocked"
            : final?.state === "missing"
              ? "Choose a final output"
              : "Building the final answer…"}
        </strong>
        <span>
          {final?.state === "missing"
            ? "Connect your branches to a document, or select a result node in the inspector."
            : "Only completed result nodes appear as the final answer. Intermediate source tables remain in Outputs."}
        </span>
        {final?.blocked?.map((item: Any) => (
          <button
            className="text-button"
            key={item.node_id}
            onClick={() => onFocus(item.node_id)}
          >
            {item.node_id}: {item.message}
          </button>
        ))}
        {!!detail.delivery?.unintegrated_research?.length && (
          <span>
            {detail.delivery.unintegrated_research.length} research branches do
            not reach the final answer. Use Integrate branches to connect them.
          </span>
        )}
      </div>
    );
  return (
    <div className="final-answer" aria-label="Completed final answer">
      <header>
        <div>
          <strong>Final answer</strong>
          <small>
            Generated by {final.results.length} completed result{" "}
            {final.results.length === 1 ? "node" : "nodes"} · sources preserved
          </small>
        </div>
        <div className="button-row">
          <button className="text-button" onClick={onExpand}>
            {expanded ? <Minimize2 size={14} /> : <Maximize2 size={14} />}
            {expanded ? "Collapse" : "Expand answer"}
          </button>
          <button
            className="button secondary small"
            disabled={exporting}
            onClick={async () => {
              setExporting(true);
              setError("");
              try {
                const file = await rpc("run.export", {
                  run_id: detail.run.id,
                  scope: "final",
                });
                await download(file.filename, file.content);
              } catch (e) {
                setError((e as Error).message);
              } finally {
                setExporting(false);
              }
            }}
          >
            {exporting ? (
              <Loader2 size={14} className="spin" />
            ) : (
              <Download size={14} />
            )}
            Export final answer
          </button>
        </div>
      </header>
      {error && (
        <p role="alert" className="warning-text">
          {error}
        </p>
      )}
      {final.results.map((node: Any) => (
        <article key={node.node_id}>
          <button
            className="final-node-link"
            onClick={() => onFocus(node.node_id)}
          >
            {node.title}
            <ArrowUpRight size={13} />
          </button>
          {Object.entries(node.outputs).map(([port, data]) => (
            <div key={port}>
              {(data as Any).kind === "text" ? (
                <div className="final-document">
                  <Markdown text={String((data as Any).value)} />
                </div>
              ) : (
                renderOutput(data as Any)
              )}
              <WebSources sources={(data as Any).sources} />
            </div>
          ))}
        </article>
      ))}
    </div>
  );
}
